import { createHmac, timingSafeEqual } from "node:crypto";
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, join, resolve, sep } from "node:path";

/**
 * Where applicant uploads live, behind a port.
 *
 * Two reasons for the indirection rather than calling R2 directly.
 *
 * The practical one: `#11` has not provisioned a bucket, and waiting would
 * have left `#21` unstarted and `file_upload` unusable in every form. With a
 * port, everything except "the bucket is genuinely private" can be built and
 * tested now, and wiring R2 later is a config change.
 *
 * The lasting one: the tests exercise a real implementation of the same
 * contract rather than a mock of it. A mocked `presignPut` would have proved
 * nothing about expiry or about a key being useless on its own, which are the
 * two properties the whole design rests on.
 */
export interface PresignedUrl {
  url: string;
  expiresAt: Date;
}

export interface FileStorage {
  /** A short-lived URL the browser may PUT to. Bytes never pass through the API. */
  presignPut(
    key: string,
    opts: { contentType: string; expiresInSeconds: number },
  ): Promise<PresignedUrl>;

  /**
   * A short-lived URL for reading one object.
   *
   * Issued **only** after the backend has authorized that specific caller for
   * that specific file. The URL is the capability; the key is not.
   */
  presignGet(
    key: string,
    opts: { expiresInSeconds: number; downloadFilename: string },
  ): Promise<PresignedUrl>;

  /** The stored size, or null if nothing was ever written to the key. */
  head(key: string): Promise<{ sizeBytes: number } | null>;

  /** The first `byteCount` bytes, for magic-byte validation at commit. */
  readPrefix(key: string, byteCount: number): Promise<Uint8Array | null>;
}

export interface LocalFileStorageOptions {
  root: string;
  /** The origin the issued URLs point at — in development, the API itself. */
  publicBaseUrl: string;
  secret: string;
}

/**
 * Filesystem-backed storage for development and tests.
 *
 * **Not for production**, and the asymmetry with R2 is worth stating: here the
 * API serves the bytes, so an upload briefly passes through it. In R2 it does
 * not, which is the point of presigning. Everything else — expiry, the key
 * being worthless without a signature, the size and format checks at commit —
 * behaves identically, which is what makes the tests above meaningful.
 */
export class LocalFileStorage implements FileStorage {
  constructor(private readonly options: LocalFileStorageOptions) {}

  /**
   * Resolves a key to a path, refusing anything that escapes the root.
   *
   * Keys are generated by us, so this should be unreachable — which is exactly
   * why it is here. The day somebody derives a key from an
   * `original_filename`, this is the line between a storage write and a write
   * to anywhere on the disk.
   */
  private pathFor(key: string): string {
    const root = resolve(this.options.root);
    const path = resolve(join(root, key));
    if (path !== root && !path.startsWith(root + sep)) {
      throw new Error("Refusing a storage key that escapes the storage root.");
    }
    return path;
  }

  private sign(key: string, expiresAtMs: number, method: "put" | "get"): string {
    return (
      createHmac("sha256", this.options.secret)
        // The method is in the signed material, so an upload URL cannot double
        // as a download URL for the same key.
        .update(`${method}\n${key}\n${expiresAtMs}`)
        .digest("base64url")
    );
  }

  private presign(
    key: string,
    method: "put" | "get",
    expiresInSeconds: number,
    extra: Record<string, string> = {},
  ): PresignedUrl {
    const expiresAtMs = Date.now() + expiresInSeconds * 1000;
    const url = new URL(`/__local-storage/${method}`, this.options.publicBaseUrl);
    url.searchParams.set("key", key);
    url.searchParams.set("exp", String(expiresAtMs));
    for (const [name, value] of Object.entries(extra)) {
      url.searchParams.set(name, value);
    }
    url.searchParams.set("sig", this.sign(key, expiresAtMs, method));
    return { url: url.toString(), expiresAt: new Date(expiresAtMs) };
  }

  presignPut(key: string, opts: { contentType: string; expiresInSeconds: number }) {
    return Promise.resolve(
      this.presign(key, "put", opts.expiresInSeconds, { type: opts.contentType }),
    );
  }

  presignGet(key: string, opts: { expiresInSeconds: number; downloadFilename: string }) {
    return Promise.resolve(
      this.presign(key, "get", opts.expiresInSeconds, { filename: opts.downloadFilename }),
    );
  }

  /**
   * Whether a query string is a signature this adapter issued, and still live.
   *
   * Returns a result rather than throwing, because every caller needs to turn
   * it into an HTTP status rather than a stack trace.
   */
  verify(search: string, method: "put" | "get"): { ok: boolean; key?: string } {
    const params = new URLSearchParams(search);
    const key = params.get("key");
    const exp = params.get("exp");
    const sig = params.get("sig");

    if (key === null || exp === null || sig === null) {
      return { ok: false };
    }
    const expiresAtMs = Number(exp);
    if (!Number.isFinite(expiresAtMs) || expiresAtMs <= Date.now()) {
      // Expiry is the whole reason a presigned URL is safe to hand to a
      // browser: a leaked one stops working.
      return { ok: false };
    }

    const expected = Buffer.from(this.sign(key, expiresAtMs, method));
    const actual = Buffer.from(sig);
    if (expected.length !== actual.length || !timingSafeEqual(expected, actual)) {
      return { ok: false };
    }
    return { ok: true, key };
  }

  /** Writes an object. In production R2 this is the browser's PUT, not ours. */
  async put(key: string, bytes: Uint8Array): Promise<void> {
    const path = this.pathFor(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, bytes);
  }

  async head(key: string): Promise<{ sizeBytes: number } | null> {
    const path = this.pathFor(key);
    try {
      const info = await stat(path);
      return { sizeBytes: info.size };
    } catch {
      // An abandoned upload — a `pending` row whose PUT never happened — is an
      // ordinary state to report rather than an error to throw.
      return null;
    }
  }

  async readPrefix(key: string, byteCount: number): Promise<Uint8Array | null> {
    const path = this.pathFor(key);
    try {
      const contents = await readFile(path);
      return new Uint8Array(contents.subarray(0, byteCount));
    } catch {
      return null;
    }
  }
}
